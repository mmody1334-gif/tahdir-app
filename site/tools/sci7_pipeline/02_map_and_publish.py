COMPILED = [(re.compile(p), lid) for p, lid in RULES]
NOISE = re.compile(r'انتهت األسئلة|^\s*[\-_]?\s*\d\s*[\-_]?\s*$|^[\s_،.\-]+$')


def classify(text):
    for rx, lid in COMPILED:
        if rx.search(text or ''):
            return lid
    return None


def q_number(text):
    """رقم السؤال إن وُجد في النص (قد يكون مدفونًا في وسطه)."""
    m = re.search(r'(?<![\d])(\d{1,2})\s*[\)\u002e]', (text or '')[:70])
    return int(m.group(1)) if m else None


def main():
    raw = json.load(open(os.path.join(WORK, 'ALL.json'), encoding='utf-8'))
    out_dir = os.path.join(IMG, 'sci7')
    os.makedirs(out_dir, exist_ok=True)

    # ---------- تصفية: نُبقي البدائل المُقيَّمة فقط ----------
    parts = []
    for it in raw:
        t = (it.get('text') or '').strip()
        if NOISE.search(t) or len(t) < 8:
            continue
        parts.append(it)

    # ---------- توريث الدرس: نتابع السؤال الأب داخل نفس الورقة ----------
    parent_lesson, parent_num = {}, {}
    lessons = []
    for it in parts:
        paper = it['paper']
        t = it.get('text') or ''
        num = q_number(t)
        if num is not None:
            parent_num[paper] = num
            lid = classify(t)
            if lid:
                parent_lesson[paper] = lid
        lid = classify(t) or parent_lesson.get(paper)
        lessons.append(lid)

    # ---------- البناء ----------
    papers, questions, unmapped = {}, [], []
    counters = Counter()
    for it, lid in zip(parts, lessons):
        paper = it['paper']
        src = it['file']
        dst = os.path.join(out_dir, it['qid'] + '.webp')
        if not os.path.exists(dst):
            shutil.copyfile(src, dst)
        pid = 'g7-' + paper.replace('-', '_')
        papers.setdefault(pid, {'year': '2025-2026', 'term': 1,
                                'session': it.get('session', ''), 'region': it.get('region', ''),
                                'total': 40})
        counters[paper] += 1
        n = q_number(it.get('text') or '')
        unit = LESSON.get(lid, ('', ''))[0]
        questions.append({
            'id': it['qid'], 'p': pid,
            'n': str(n) if n else ('%s-%d' % (paper, counters[paper])),
            'm': int(it['marks']),
            't': 'mcq' if it['marks'] == 1 else 'short',
            'x': (it.get('text') or '').strip()[:1500], 'a': '', 'as': 'ms', 'c': '', 'ao': '',
            'u': unit, 'l': lid, 'l2': None,
            'im': 'sci7/%s.webp' % it['qid'], 'w': it['w'], 'h': it['h'],
        })
        if not lid:
            unmapped.append((it['seq'], it['marks'], (it.get('text') or '')[:70]))

    finals = json.load(open(os.path.join(DATA, 'finals.json'), encoding='utf-8'))
    finals['العلوم|السابع'] = {
        'subject': 'العلوم', 'grade': 'السابع',
        'units': {u: UNIT_NAMES[u] for u in sorted({q['u'] for q in questions if q['u']})},
        'papers': papers, 'q': questions,
    }
    with open(os.path.join(DATA, 'finals.json'), 'w', encoding='utf-8') as f:
        json.dump(finals, f, ensure_ascii=False, separators=(',', ':'))

    print('المفردات: %d | مجموع الدرجات: %d | بلا درس: %d' %
          (len(questions), sum(q['m'] for q in questions), len(unmapped)))
    dist = Counter(q['m'] for q in questions)
    print('توزيع الدرجات: %s' % dict(sorted(dist.items())))
    print('\nالوحدات:')
    cu = Counter(q['u'] for q in questions)
    for u in sorted(x for x in cu if x):
        print('   الوحدة %s — %-34s %d' % (u, UNIT_NAMES[u], cu[u]))
    if '' in cu:
        print('   بلا وحدة: %d' % cu[''])
    print('\nالدروس المغطّاة (%d):' % len({q['l'] for q in questions if q['l']}))
    cl = Counter(q['l'] for q in questions)
    for lid in sorted(x for x in cl if x):
        print('   %-4s وحدة %s  %-38s %d' % (lid, LESSON[lid][0], LESSON[lid][1], cl[lid]))
    if unmapped:
        print('\nبلا درس:')
        for s, mk, t in unmapped:
            print('   #%-3d درجة=%-2d %s' % (s, mk, t.replace('\n', ' ')))


if __name__ == '__main__':
    main()
