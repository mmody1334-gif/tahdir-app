STOP = set('''في من على إلى عن أن أنّ إن إذا ما ماذا لماذا كيف متى هل هذا هذه ذلك تلك هو هي هم هن أنا نحن أنت أنتم و أو ثم بل لا لم لن قد كان يكن مع عند لدى حتى كل بعض غير بين حيث كي مثل ب عبر بـ ال يا أي أيه أما إما لـ س ي في ولست نوظف يتم يقُذ?'''.split())

def norm(t):
    t = re.sub(r'[\u064B-\u0652]', '', str(t or ''))          # حذف التشكيل
    t = t.replace('أ', 'ا').replace('إ', 'ا').replace('آ', 'ا').replace('ى', 'ي').replace('ة', 'ه')
    t = re.sub(r'\s+', ' ', t).strip()
    return t

def stem_clean(q):
    q = re.sub(r'^[\s\=\-\d\.\_\)\*]+', '', str(q or '')).strip()
    return re.sub(r'\s+', ' ', q)

def tokens(t):
    out = []
    for w in norm(t).split():
        w = w.strip('.,،؛:();«»؟!"\'-–_')
        if len(w) >= 3 and w not in STOP:
            if w.startswith('ال') and len(w) > 4: w = w[2:]
            if w.startswith('و') and len(w) > 4: w = w[1:]
            out.append(w)
    return out

def score(q, a):
    tq = set(tokens(q)); ta = set(tokens(a))
    if not tq or not ta: return 0
    ov = tq & ta
    return len(ov) + (1 if len(ov) >= max(2, len(tq) // 3) else 0)

def lines_of(txt):
    out = []
    for ln in str(txt or '').split('\n'):
        ln = re.sub(r'^[\s\-\=\_\d\.\)\*\u0660-\u0669]+', '', ln.strip())
        ln = ln.strip()
        if len(ln) >= 15 and not ln.endswith('؟') and not ln.rstrip().endswith(':'):
            out.append(ln)
    return out

