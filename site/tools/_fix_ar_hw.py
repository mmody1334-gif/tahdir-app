def concepts_text(concepts):
    """تنظيف حقل المفاهيم ليصلح إجابةً لسؤال «ما أبرز المفاهيم...»."""
    c = re.sub(r'\s+', ' ', str(concepts or '')).strip()
    c = re.sub(r'^[\*\d\.\s]+', '', c).strip()          # إزالة النجوم والترقيم البادئ
    c = re.sub(r'\.{3,}', '،', c)                        # النقاط العالقة
    c = re.sub(r'^المفاهيم والأفكار المحورية لدرس\s*\(.*?\)\s*:\s*', '', c)
    c = re.sub(r'^يُتوقع من الطالب في هذا الدرس أن:\s*', '', c)
    return c.strip()

