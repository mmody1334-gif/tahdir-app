BLOCK_RE = re.compile(r'^#(\d+)\b')
for lid, lines in ADD.items():
    done = False
    for fn in sorted(os.listdir(ROOT)):
        if not fn.endswith('.txt'): continue
        p = os.path.join(ROOT, fn)
        rows = io.open(p, encoding='utf-8').read().split('\n')
        si = None
        for k, r in enumerate(rows):
            m = BLOCK_RE.match(r.strip())
            if m and int(m.group(1)) == lid:
                si = k; break
        if si is None: continue
        ei = len(rows)
        for k in range(si + 1, len(rows)):
            if rows[k].strip().startswith('#'):
                ei = k; break
        rows[ei:ei] = lines
        io.open(p, 'w', encoding='utf-8', newline='\n').write('\n'.join(rows))
        print('added %d -> %s (%d lines)' % (lid, fn, len(lines)))
        done = True
        break
    if not done:
        print('MISSING block for lesson', lid)

