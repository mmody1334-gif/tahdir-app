def fix(t):
    for a, b in FIX: t = t.replace(a, b)
    # أقواس معكوسة من نسخ الوورد: ) نص ( → ( نص )
    t = re.sub(r'\)([^()\n]{1,80})\(', lambda m: '(' + m.group(1) + ')', t)
    out = []
    for line in t.split('\n'):
        d = 0; cs = []
        for ch in line:
            if ch == ')' and d == 0: ch = '('
            if ch == '(': d += 1
            elif ch == ')': d -= 1
            cs.append(ch)
        out.append(''.join(cs))
    t = '\n'.join(out)
    t = re.sub(r'\(\s+', '(', t); t = re.sub(r'\s+\)', ')', t)
    t = re.sub(r'\s+([،.:؟])', r'\1', t)
    t = re.sub(r'(?<![\u0621-\u064a])علي (?=[\u0621-\u064a])', 'على ', t)
    t = re.sub(r'(?<![\u0621-\u064a])الي (?=[\u0621-\u064a])', 'إلى ', t)
    t = re.sub(r'(?m)^(التعلم القبلي|التمهيد|المفاهيم)\s*[:/]?\s*$\n?', '', t)
    t = re.sub(r'[ \t]{2,}', ' ', t)
    t = re.sub(r'\n{2,}', '\n', t)
    return t.strip()
def outcomes(t):
    L = [x for x in t.split('\n') if x.strip() and not re.match(r'^(في نهاية الدرس|ينبغي للطالب|ينبغي)', x.strip())]
    L = [re.sub(r'^\s*[\d١-٩]+\s*[-:.)]\s*', '', x).strip(' .') for x in L]
    M = []
    for x in L:
        if M and not re.match(r'^[يتأ]', x): M[-1] = M[-1] + ' ' + x
        else: M.append(x)
    L = M
