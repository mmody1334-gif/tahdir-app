def split_pre(t):
    m = re.search(r'المفاهيم\s*:?', t)
    if not m: return '', t
    before = t[:m.start()]; after = t[m.end():]
    m2 = re.search(r'\n?(الإعداد البدني|الاعداد البدني)', after)
    if m2:
        conc = after[:m2.start()]; before = before + '\n' + after[m2.start():]
    else: conc = after
    conc = re.sub(r'\s*[-–]+\s*|\n|\*', '، ', conc).strip('،: ')
    conc = re.sub(r'[()_.]', '،', conc)
    conc = re.sub(r'\s*،\s*', '، ', conc)
    conc = re.sub(r'(،\s*)+', '، ', conc).strip('، ')
    return conc, before
