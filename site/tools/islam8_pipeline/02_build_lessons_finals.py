def lesson_for(ans, page):
    best, best_n = None, 0
    for lid in KW:
        n = sum(1 for w in KW[lid] if w in ans)
        if n > best_n:
            best, best_n = lid, n
    if best:
        return best
    # لا كلمة مفتاحية ⇒ نستخدم صفحة الكتاب ونطاقات الدروس
    for lid, (a, b) in PAGE_HINT.items():
        if a <= page <= b:
            return lid
    return None


